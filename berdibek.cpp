#include <iostream>
#include <string>

using namespace std;

int main() {
    // 1. Атты енгізіп, сәлемдесу хабарламасын шығару
    string name;
    cout << "1. Есіміңізді енгізіңіз: ";
    cin >> name;
    cout << "Сәлем, " << name << "!" << endl << endl;

    // 2. Жасты енгізіп, 14 жылдан кейінгі жасты шығару
    int age;
    cout << "2. Жасыңызды енгізіңіз: ";
    cin >> age;
    cout << "14 жылдан кейінгі жасыңыз: " << age + 14 << endl << endl;

    // 3. Екі санды енгізіп, олардың айырмасын шығару
    double a, b;
    cout << "3. Екі сан енгізіңіз (айырмасын табу үшін): ";
    cin >> a >> b;
    cout << "Айырмасы (а - b): " << a - b << endl << endl;

    // 4. Екі санды енгізіп, орташа мәнін табу
    double x, y;
    cout << "4. Екі сан енгізіңіз (орташа мәнін табу үшін): ";
    cin >> x >> y;
    cout << "Орташа мәні: " << (x + y) / 2.0 << endl << endl;

    // 5. Қашықтықты километрмен енгізіп, метрге айналдыру
    double km;
    cout << "5. Қашықтықты километрмен енгізіңіз: ";
    cin >> km;
    cout << "Метрмен: " << km * 1000 << " м" << endl;

    return 0;
}
